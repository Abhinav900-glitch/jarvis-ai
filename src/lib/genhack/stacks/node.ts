// ---------------------------------------------------------------------------
// Node + TypeScript HTTP API blueprint.
//
// No framework, no build step needed to read it: node:http, a small router, and
// one module per entity with routes → service → repository → schema. The point
// is that every file is load-bearing and the import graph closes, because the
// checker resolves every relative import in the project it just wrote.
// ---------------------------------------------------------------------------

import {
  file,
  pascal,
  type BuildContext,
  type Entity,
  type GenFile,
} from "../types";

const pkg = (ctx: BuildContext) =>
  JSON.stringify(
    {
      name: ctx.name + "-api",
      private: true,
      version: "0.1.0",
      type: "module",
      scripts: {
        dev: "node --watch --experimental-strip-types src/server.ts",
        start: "node --experimental-strip-types src/server.ts",
        test: "node --experimental-strip-types --test test/",
        typecheck: "tsc --noEmit",
      },
      devDependencies: { "@types/node": "^22.9.0", typescript: "^5.6.3" },
    },
    null,
    2,
  );

