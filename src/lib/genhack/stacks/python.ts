// ---------------------------------------------------------------------------
// Python CLI + package blueprint.
//
// Same shape as the other stacks — one feature package per entity, a store, a
// service, validators, formatters, commands, tests — in plain Python with no
// dependencies, so the zip runs anywhere with a 3.11 interpreter.
// ---------------------------------------------------------------------------

import {
  file,
  pascal,
  type BuildContext,
  type Entity,
  type GenFile,
} from "../types";

const pkgName = (ctx: BuildContext) => ctx.name.replace(/-/g, "_");

function scaffold(ctx: BuildContext): GenFile[] {
  const pkg = pkgName(ctx);
  const brief = ctx.brief.replace(/[{}]/g, "").slice(0, 300);
  const primary = ctx.entities[0];
  const P = pascal(primary.key);

  const builders = ctx.entities.map(
    (entity) =>
      "from ." + entity.key + ".cli import build_parser as build_" + entity.key + ", run as run_" + entity.key,
  );
  const builderMap = ctx.entities.map((entity) => '    "' + entity.key + '": build_' + entity.key + ",");
  const runnerMap = ctx.entities.map((entity) => '    "' + entity.key + '": run_' + entity.key + ",");

  return [
    file("pyproject.toml", "toml", "Packaging and pytest config", [
      "[project]",
      'name = "' + ctx.name + '"',
      'version = "0.1.0"',
      'description = "' + brief.replace(/"/g, "") + '"',
      'requires-python = ">=3.11"',
      "dependencies = []",
      "",
      "[project.scripts]",
      pkg + ' = "' + pkg + '.__main__:main"',
      "",
      "[tool.pytest.ini_options]",
      'pythonpath = ["src"]',
      'testpaths = ["tests", "src"]',
      'addopts = "-q"',
    ]),
    file("src/" + pkg + "/__init__.py", "python", "Package metadata", [
      '"""' + ctx.title + '."""',
      "",
      '__version__ = "0.1.0"',
    ]),
    file("src/" + pkg + "/__main__.py", "python", "Module entry point", [
      '"""python -m ' + pkg + '"""',
      "",
      "from .cli import main",
      "",
      'if __name__ == "__main__":',
      "    raise SystemExit(main())",
    ]),
    file("src/" + pkg + "/cli.py", "python", "Argument parsing", [
      '"""Command line entry point."""',
      "",
      "from __future__ import annotations",
      "",
      "import argparse",
      "import sys",
      "",
      ...builders,
      "",
      "",
      "def main(argv: list[str] | None = None) -> int:",
      '    parser = argparse.ArgumentParser(prog="' + ctx.name + '", description="' + brief.replace(/"/g, "") + '")',
      '    features = parser.add_subparsers(dest="feature")',
      "",
      "    builders = {",
      ...builderMap,
      "    }",
      "    for name, build in builders.items():",
      "        child = features.add_parser(name, help=name + \" commands\")",
      "        build(child)",
      "",
      "    args = parser.parse_args(argv)",
      "    if not args.feature:",
      "        parser.print_help()",
      "        return 0",
      "",
      "    runners = {",
      ...runnerMap,
      "    }",
      "    try:",
      "        return runners[args.feature](args)",
      "    except KeyError:",
      '        print("unknown feature: " + args.feature, file=sys.stderr)',
      "        return 2",
    ]),
    file("src/" + pkg + "/store.py", "python", "In-memory table", [
      '"""A small generic table, so every feature stores rows the same way."""',
      "",
      "from __future__ import annotations",
      "",
      "from typing import Generic, TypeVar",
      "",
      "T = TypeVar(\"T\")",
      "",
      "",
      "class Table(Generic[T]):",
      "    def __init__(self, name: str) -> None:",
      "        self.name = name",
      "        self._rows: dict[str, T] = {}",
      "",
      "    def all(self) -> list[T]:",
      "        return list(self._rows.values())",
      "",
      "    def get(self, key: str) -> T | None:",
      "        return self._rows.get(key)",
      "",
      "    def put(self, key: str, value: T) -> T:",
      "        self._rows[key] = value",
      "        return value",
      "",
      "    def delete(self, key: str) -> bool:",
      "        return self._rows.pop(key, None) is not None",
      "",
      "    def __len__(self) -> int:",
      "        return len(self._rows)",
    ]),
    file("src/" + pkg + "/errors.py", "python", "Error types", [
      '"""Errors carry a stable code so the CLI can map them to exit statuses."""',
      "",
      "",
      "class AppError(Exception):",
      '    code = "error"',
      "",
      "",
      "class NotFoundError(AppError):",
      '    code = "not_found"',
      "",
      "    def __init__(self, what: str) -> None:",
      "        super().__init__(what + \" not found\")",
      "",
      "",
      "class ConflictError(AppError):",
      '    code = "conflict"',
      "",
      "",
      "class ValidationError(AppError):",
      '    code = "invalid_input"',
    ]),
    file("src/" + pkg + "/ids.py", "python", "Id generation", [
      '"""Opaque ids, prefixed so a stray id is readable in logs."""',
      "",
      "from uuid import uuid4",
      "",
      "",
      "def new_id(prefix: str) -> str:",
      '    return prefix + "_" + uuid4().hex[:8]',
    ]),
    file("src/" + pkg + "/config.py", "python", "Settings", [
      '"""Settings from the environment, with sane defaults."""',
      "",
      "from __future__ import annotations",
      "",
      "import os",
      "from dataclasses import dataclass",
      "",
      "",
      "@dataclass(frozen=True)",
      "class Settings:",
      "    data_dir: str = os.environ.get(\"DATA_DIR\", \"data\")",
      "    log_level: str = os.environ.get(\"LOG_LEVEL\", \"info\")",
      "    page_size: int = int(os.environ.get(\"PAGE_SIZE\", \"20\"))",
      "",
      "",
      "settings = Settings()",
    ]),
    file("src/" + pkg + "/logging.py", "python", "Logging setup", [
      '"""One place that configures logging, so libraries stay quiet."""',
      "",
      "from __future__ import annotations",
      "",
      "import logging",
      "",
      "",
      "def configure(level: str = \"info\") -> logging.Logger:",
      "    logging.basicConfig(",
      "        level=getattr(logging, level.upper(), logging.INFO),",
      "        format=\"%(levelname)s %(message)s\",",
      "    )",
      '    logging.getLogger("urllib3").setLevel(logging.WARNING)',
      '    return logging.getLogger("' + ctx.name + '")',
    ]),
    file("src/" + pkg + "/formatters.py", "python", "Shared display helpers", [
      '"""Formatting shared by every feature."""',
      "",
      "from __future__ import annotations",
      "",
      "from datetime import datetime",
      "",
      "",
      "def money(amount: float) -> str:",
      '    return "$" + format(amount, ",.2f")',
      "",
      "",
      "def iso(moment: datetime) -> str:",
      "    return moment.isoformat(timespec=\"seconds\")",
      "",
      "",
      "def table(headers: list[str], rows: list[list[str]]) -> str:",
      "    widths = [len(header) for header in headers]",
      "    for row in rows:",
      "        for index, cell in enumerate(row):",
      "            widths[index] = max(widths[index], len(cell))",
      "",
      "    def line(values: list[str]) -> str:",
      '        return "  ".join(value.ljust(widths[index]) for index, value in enumerate(values))',
      "",
      '    body = [line(headers)] + [line(row) for row in rows]',
      '    return "\\n".join(body)',
    ]),
    file("src/" + pkg + "/pagination.py", "python", "Paging", [
      '"""Page a list without pulling in a dependency."""',
      "",
      "from __future__ import annotations",
      "",
      "from typing import TypeVar",
      "",
      "T = TypeVar(\"T\")",
      "",
      "",
      "def paginate(items: list[T], page: int = 0, size: int = 20) -> list[T]:",
      "    if page < 0 or size < 1:",
      '        raise ValueError("page and size must be positive")',
      "    start = page * size",
      "    return items[start : start + size]",
    ]),
    file("src/" + pkg + "/validators.py", "python", "Shared input checks", [
      '"""Validation helpers used by every feature."""',
      "",
      "from __future__ import annotations",
      "",
      "from typing import Any",
      "",
      "from .errors import ValidationError",
      "",
      "",
      "def as_str(value: Any, field: str) -> str:",
      "    text = str(value or \"\").strip()",
      "    if not text:",
      "        raise ValidationError(field + \" is required\")",
      "    return text",
      "",
      "",
      "def as_float(value: Any, field: str) -> float:",
      "    try:",
      "        number = float(value)",
      "    except (TypeError, ValueError) as exc:",
      "        raise ValidationError(field + \" must be a number\") from exc",
      "    if number < 0:",
      "        raise ValidationError(field + \" cannot be negative\")",
      "    return number",
      "",
      "",
      "def as_choice(value: Any, allowed: tuple[str, ...], field: str) -> str:",
      "    text = str(value or allowed[0]).strip().lower()",
      "    if text not in allowed:",
      '        raise ValidationError(field + " must be one of " + ", ".join(allowed))',
      "    return text",
    ]),
    file("tests/conftest.py", "python", "Test bootstrap", [
      '"""Make src importable when pytest is run straight from the repo root."""',
      "",
      "import sys",
      "from pathlib import Path",
      "",
      "SRC = Path(__file__).resolve().parents[1] / \"src\"",
      "if str(SRC) not in sys.path:",
      "    sys.path.insert(0, str(SRC))",
    ]),
    file("tests/test_cli.py", "python", "CLI smoke tests", [
      '"""The CLI must answer --help and reject an unknown feature."""',
      "",
      "import pytest",
      "",
      "from " + pkg + ".cli import main",
      "",
      "",
      "def test_help_exits_zero(capsys) -> None:",
      "    assert main([]) == 0",
      "    captured = capsys.readouterr()",
      '    assert "usage" in captured.out.lower()',
      "",
      "",
      "def test_unknown_feature_returns_two() -> None:",
      "    with pytest.raises(SystemExit):",
      "        main([\"nope\"])",
    ]),
    file("tests/test_store.py", "python", "Store tests", [
      '"""The table is the base every repository builds on."""',
      "",
      "from " + pkg + ".store import Table",
      "",
      "",
      "def test_put_get_delete() -> None:",
      "    table: Table[str] = Table(\"demo\")",
      "    table.put(\"a\", \"first\")",
      "    assert table.get(\"a\") == \"first\"",
      "    assert table.delete(\"a\") is True",
      "    assert table.get(\"a\") is None",
      "",
      "",
      "def test_all_is_a_copy() -> None:",
      "    table: Table[int] = Table(\"numbers\")",
      "    table.put(\"one\", 1)",
      "    snapshot = table.all()",
      "    snapshot.append(2)",
      "    assert len(table.all()) == 1",
    ]),
    file("scripts/seed.py", "python", "Sample data", [
      '"""Insert a few sample rows so the CLI has something to list."""',
      "",
      "from " + pkg + "." + primary.key + ".models import " + P + "Draft",
      "from " + pkg + "." + primary.key + ".service import " + P + "Service",
      "",
      "",
      "def main() -> None:",
      "    service = " + P + "Service()",
      '    for index in range(1, 4):',
      "        service.create(" + P + "Draft(name=\"Sample \" + str(index), amount=index * 10))",
      '    print("seeded " + str(len(service.list())) + " rows")',
      "",
      "",
      'if __name__ == "__main__":',
      "    main()",
    ]),
    file("README.md", "markdown", "Package guide", [
      "# " + ctx.title,
      "",
      "> " + brief,
      "",
      "A dependency-free Python CLI and package: one feature module per entity,",
      "with models, repositories, services, validators, formatters and tests.",
      "",
      "## Run",
      "",
      "```bash",
      "PYTHONPATH=src python -m " + pkg + " --help",
      "PYTHONPATH=src python -m " + pkg + " " + ctx.entities[0].key + " list",
      "pytest",
      "```",
      "",
      "## Features",
      "",
      ctx.entities.map((entity) => "- `" + entity.key + "` — models, service, CLI, tests.").join("\n"),
    ]),
    file(".gitignore", "text", "Ignored paths", [
      "__pycache__",
      "*.pyc",
      ".pytest_cache",
      "dist",
      "build",
      "*.egg-info",
    ]),
    file(".env.example", "text", "Environment template", [
      "DATA_DIR=data",
      "LOG_LEVEL=info",
      "PAGE_SIZE=20",
    ]),
    file("Makefile", "text", "Common commands", [
      ".PHONY: install test lint run",
      "",
      "install:",
      "\tpip install -e .",
      "",
      "test:",
      "\tPYTHONPATH=src pytest",
      "",
      "run:",
      "\tPYTHONPATH=src python -m " + pkg + " --help",
    ]),
    file("Dockerfile", "docker", "Runtime image", [
      "FROM python:3.12-slim",
      "WORKDIR /app",
      "COPY . .",
      "RUN pip install --no-cache-dir -e .",
      'ENTRYPOINT ["python", "-m", "' + pkg + '"]',
    ]),
    file(".github/workflows/ci.yml", "yaml", "Tests", [
      "name: ci",
      "on: push",
      "jobs:",
      "  test:",
      "    runs-on: ubuntu-latest",
      "    steps:",
      "      - uses: actions/checkout@v4",
      "      - uses: actions/setup-python@v5",
      "        with:",
      "          python-version: 3.12",
      "      - run: pip install pytest",
      "      - run: PYTHONPATH=src pytest",
    ]),
    file("docs/ARCHITECTURE.md", "markdown", "Layers", [
      "# Architecture",
      "",
      "`cli.py` parses → feature service applies rules → repository reads the store.",
      "",
      "## Rules",
      "",
      "1. Commands never touch a table directly; they call a service.",
      "2. Services raise `AppError` subclasses, never bare exceptions.",
      "3. Validators turn raw input into typed drafts.",
      "4. Every feature has at least one test that runs without a network.",
    ]),
    file("docs/CLI.md", "markdown", "Commands", [
      "# CLI",
      "",
      "```bash",
      "PYTHONPATH=src python -m " + pkg + " <feature> <command>",
      "```",
      "",
      "Features: " + ctx.entities.map((entity) => "`" + entity.key + "`").join(", ") + ".",
      "",
      "Each feature exposes `list`, `show <id>` and `delete <id>`.",
    ]),
    file("CHANGELOG.md", "markdown", "History", [
      "# Changelog",
      "",
      "## 0.1.0",
      "",
      "- First version with " + ctx.entities.length + " feature packages.",
    ]),
  ];
}

function entityFiles(entity: Entity): GenFile[] {
  const key = entity.key;
  const P = pascal(key);
  const base = "src/" + "PKG" + "/" + key;

  return [
    file(base + "/__init__.py", "python", "Public surface for " + key, [
      '"""' + entity.title + ' feature."""',
      "",
      "from .models import " + P + ", " + P + "Draft",
      "from .service import " + P + "Service",
      "",
      '__all__ = ["' + P + '", "' + P + 'Draft", "' + P + 'Service"]',
    ]),
    file(base + "/models.py", "python", "Dataclasses for " + key, [
      '"""' + entity.title + ' data."""',
      "",
      "from __future__ import annotations",
      "",
      "from dataclasses import dataclass, field",
      "from datetime import datetime, timezone",
      "",
      "",
      "def now() -> datetime:",
      "    return datetime.now(timezone.utc)",
      "",
      "",
      "@dataclass(slots=True)",
      "class " + P + ":",
      "    id: str",
      "    name: str",
      "    status: str",
      "    amount: float",
      "    created_at: datetime = field(default_factory=now)",
      "    updated_at: datetime = field(default_factory=now)",
      "",
      "",
      "@dataclass(slots=True)",
      "class " + P + "Draft:",
      "    name: str",
      '    status: str = "draft"',
      "    amount: float = 0.0",
      "",
      "    def normalised(self) -> \"" + P + "Draft\":",
      "        return " + P + "Draft(",
      "            name=self.name.strip(),",
      "            status=self.status,",
      "            amount=round(self.amount, 2),",
      "        )",
    ]),
    file(base + "/repository.py", "python", "Storage for " + key, [
      '"""Only this module touches the ' + key + ' table."""',
      "",
      "from __future__ import annotations",
      "",
      "from ..store import Table",
      "from .models import " + P,
      "",
      'TABLE: Table[' + P + '] = Table("' + key + '")',
      "",
      "",
      "class " + P + "Repository:",
      "    def list(self) -> list[" + P + "]:",
      "        return TABLE.all()",
      "",
      "    def find(self, row_id: str) -> " + P + " | None:",
      "        return TABLE.get(row_id)",
      "",
      "    def add(self, row: " + P + ") -> " + P + ":",
      "        return TABLE.put(row.id, row)",
      "",
      "    def remove(self, row_id: str) -> bool:",
      "        return TABLE.delete(row_id)",
    ]),
    file(base + "/service.py", "python", "Rules for " + key, [
      '"""' + entity.title + ' business rules."""',
      "",
      "from __future__ import annotations",
      "",
      "from ..errors import ConflictError, NotFoundError",
      "from ..ids import new_id",
      "from .models import " + P + ", " + P + "Draft, now",
      "from .repository import " + P + "Repository",
      "",
      "REPO = " + P + "Repository()",
      "",
      "",
      "class " + P + "Service:",
      "    def list(self) -> list[" + P + "]:",
      "        return REPO.list()",
      "",
      "    def get(self, row_id: str) -> " + P + ":",
      "        found = REPO.find(row_id)",
      "        if found is None:",
      '            raise NotFoundError("' + entity.singular + '")',
      "        return found",
      "",
      "    def create(self, draft: " + P + "Draft) -> " + P + ":",
      "        clean = draft.normalised()",
      "        if any(row.name == clean.name for row in REPO.list()):",
      '            raise ConflictError("' + entity.singular + ' with that name already exists")',
      "        return REPO.add(",
      "            " + P + "(",
      '                id=new_id("' + key.slice(0, 3) + '"),',
      "                name=clean.name,",
      "                status=clean.status,",
      "                amount=clean.amount,",
      "            )",
      "        )",
      "",
      "    def update(self, row_id: str, draft: " + P + "Draft) -> " + P + ":",
      "        current = self.get(row_id)",
      "        clean = draft.normalised()",
      "        current.name = clean.name",
      "        current.status = clean.status",
      "        current.amount = clean.amount",
      "        current.updated_at = now()",
      "        return REPO.add(current)",
      "",
      "    def delete(self, row_id: str) -> None:",
      "        if not REPO.remove(row_id):",
      '            raise NotFoundError("' + entity.singular + '")',
    ]),
    file(base + "/validators.py", "python", "Input parsing for " + key, [
      '"""Turn raw CLI input into a typed draft."""',
      "",
      "from __future__ import annotations",
      "",
      "from typing import Any, Mapping",
      "",
      "from ..validators import as_choice, as_float, as_str",
      "from .models import " + P + "Draft",
      "",
      'STATUSES = ("draft", "active", "closed")',
      "",
      "",
      "def parse_draft(payload: Mapping[str, Any]) -> " + P + "Draft:",
      '    return ' + P + 'Draft(',
      '        name=as_str(payload.get("name"), "name"),',
      '        status=as_choice(payload.get("status"), STATUSES, "status"),',
      '        amount=as_float(payload.get("amount", 0), "amount"),',
      "    )",
    ]),
    file(base + "/formatters.py", "python", "Display strings for " + key, [
      '"""Format ' + key + ' for the terminal."""',
      "",
      "from __future__ import annotations",
      "",
      "from ..formatters import money",
      "from .models import " + P,
      "",
      "",
      "def describe(row: " + P + ") -> str:",
      '    return row.name + " (" + row.status + ", " + money(row.amount) + ")"',
      "",
      "",
      "def summary(rows: list[" + P + "]) -> str:",
      "    if not rows:",
      '        return "no ' + key + '"',
      "    total = sum(row.amount for row in rows)",
      '    return str(len(rows)) + " ' + key + ' worth " + money(total)',
    ]),
    file(base + "/cli.py", "python", "Commands for " + key, [
      '"""`' + key + '` commands."""',
      "",
      "from __future__ import annotations",
      "",
      "import argparse",
      "",
      "from ..formatters import table",
      "from .formatters import describe, summary",
      "from .service import " + P + "Service",
      "",
      "SERVICE = " + P + "Service()",
      "",
      "",
      "def build_parser(parser: argparse.ArgumentParser) -> None:",
      '    commands = parser.add_subparsers(dest="command")',
      "",
      '    commands.add_parser("list", help="list ' + key + '")',
      "",
      '    show = commands.add_parser("show", help="show one")',
      '    show.add_argument("row_id")',
      "",
      '    delete = commands.add_parser("delete", help="delete one")',
      '    delete.add_argument("row_id")',
      "",
      "",
      "def run(args: argparse.Namespace) -> int:",
      '    if args.command == "list":',
      "        rows = SERVICE.list()",
      "        print(summary(rows))",
      '        print(table(["id", "detail"], [[row.id, describe(row)] for row in rows]))',
      "        return 0",
      '    if args.command == "show":',
      "        print(describe(SERVICE.get(args.row_id)))",
      "        return 0",
      '    if args.command == "delete":',
      "        SERVICE.delete(args.row_id)",
      '        print("deleted " + args.row_id)',
      "        return 0",
      "    return 1",
    ]),
    // The tests use relative imports (`..service`), which only works inside a
    // package — so the folder needs its own __init__.
    file(base + "/tests/__init__.py", "python", "Marks the tests as a package", [
      '"""Tests for the ' +
        key +
        ' feature."""',
    ]),
    file(base + "/tests/test_" + key + ".py", "python", "Service tests for " + key, [
      '"""' + entity.title + ' service behaviour."""',
      "",
      "from ..service import " + P + "Service",
      "from ..validators import parse_draft",
      "",
      "",
      "def test_create_then_read() -> None:",
      "    service = " + P + "Service()",
      '    created = service.create(parse_draft({"name": "Alpha", "status": "active", "amount": 10}))',
      '    assert service.get(created.id).name == "Alpha"',
      "",
      "",
      "def test_duplicate_name_conflicts() -> None:",
      "    service = " + P + "Service()",
      '    service.create(parse_draft({"name": "Beta", "amount": 1}))',
      "    try:",
      '        service.create(parse_draft({"name": "Beta", "amount": 2}))',
      "    except Exception as error:",
      '        assert "already exists" in str(error)',
      "    else:",
      '        raise AssertionError("expected a conflict")',
      "",
      "",
      "def test_delete_removes_row() -> None:",
      "    service = " + P + "Service()",
      '    created = service.create(parse_draft({"name": "Gamma", "amount": 3}))',
      "    service.delete(created.id)",
      "    assert created.id not in [row.id for row in service.list()]",
    ]),
  ];
}

export function pythonFiles(ctx: BuildContext): GenFile[] {
  const pkg = pkgName(ctx);
  const files = [...scaffold(ctx), ...ctx.entities.flatMap((entity) => entityFiles(entity))];
  // The entity generators do not know the package name, so it is substituted
  // into paths here rather than threaded through every template.
  return files.map((entry) => ({ ...entry, path: entry.path.replace("/PKG/", "/" + pkg + "/") }));
}
