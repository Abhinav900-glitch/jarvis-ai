function entityFiles(entity: Entity): GenFile[] {
  const key = entity.key;
  const Title = pascal(key);
  const base = "src/features/" + key;
  const statuses = '"draft" | "active" | "closed"';
  const statusList = ["draft", "active", "closed"];

  return [
    file(base + "/types.ts", "typescript", "Types and defaults for " + key, [
      "export interface " + Title + " {",
      "  id: string;",
      "  name: string;",
      "  status: " + statuses + ";",
      "  amount: number;",
      "  createdAt: string;",
      "  updatedAt: string;",
      "}",
      "",
      "export type " + Title + "Draft = Pick<" + Title + ", \"name\" | \"status\" | \"amount\">;",
      "",
      "export const " + Title.toUpperCase() + "_STATUSES: " + Title + "[\"status\"][] = [",
      statusList.map((status) => '  "' + status + '",').join("\n"),
      "];",
      "",
      "export function empty" + Title + "Draft(): " + Title + "Draft {",
      '  return { name: "", status: "draft", amount: 0 };',
      "}",
    ]),
    file(base + "/api.ts", "typescript", "HTTP calls for " + key, [
      'import { request } from "../../lib/api";',
      'import type { ' + Title + ', ' + Title + 'Draft } from "./types";',
      "",
      "export function list" + Title + "s(signal?: AbortSignal): Promise<" + Title + "[]> {",
      "  return request<" + Title + "[]>(\"/" + key + "\", { signal });",
      "}",
      "",
      "export function create" + Title + "(draft: " + Title + "Draft): Promise<" + Title + "> {",
      "  return request<" + Title + ">(\"/" + key + "\", { method: \"POST\", body: draft });",
      "}",
      "",
      "export function update" + Title + "(id: string, draft: " + Title + "Draft): Promise<" + Title + "> {",
      "  return request<" + Title + ">(\"/" + key + "/\" + encodeURIComponent(id), {",
      "    method: \"PUT\",",
      "    body: draft,",
      "  });",
      "}",
      "",
      "export function delete" + Title + "(id: string): Promise<void> {",
      "  return request<void>(\"/" + key + "/\" + encodeURIComponent(id), { method: \"DELETE\" });",
      "}",
    ]),
    file(base + "/hooks.ts", "typescript", "State and mutations for " + key, [
      'import { useCallback, useEffect, useState } from "react";',
      'import { create' + Title + ", delete" + Title + ", list" + Title + "s } from \"./api\";",
      'import type { ' + Title + ', ' + Title + 'Draft } from "./types";',
      "",
      "export function use" + Title + "s() {",
      "  const [items, setItems] = useState<" + Title + "[]>([]);",
      "  const [loading, setLoading] = useState(true);",
      "  const [error, setError] = useState<string | null>(null);",
      "",
      "  const reload = useCallback(async () => {",
      "    setLoading(true);",
      "    try {",
      "      setItems(await list" + Title + "s());",
      "      setError(null);",
      "    } catch (err) {",
      '      setError(err instanceof Error ? err.message : "Could not load ' + key + '");',
      "    } finally {",
      "      setLoading(false);",
      "    }",
      "  }, []);",
      "",
      "  useEffect(() => {",
      "    void reload();",
      "  }, [reload]);",
      "",
      "  const add = useCallback(async (draft: " + Title + "Draft) => {",
      "    const created = await create" + Title + "(draft);",
      "    setItems((current) => [created, ...current]);",
      "    return created;",
      "  }, []);",
      "",
      "  const remove = useCallback(async (id: string) => {",
      "    await delete" + Title + "(id);",
      "    setItems((current) => current.filter((item) => item.id !== id));",
      "  }, []);",
      "",
      "  return { items, loading, error, reload, add, remove };",
      "}",
    ]),
    file(base + "/selectors.ts", "typescript", "Pure queries for " + key, [
      'import type { ' + Title + ' } from "./types";',
      "",
      "export function active" + Title + "s(items: " + Title + "[]): " + Title + "[] {",
      '  return items.filter((item) => item.status !== "closed");',
      "}",
      "",
      "export function totalAmount(items: " + Title + "[]): number {",
      "  return items.reduce((sum, item) => sum + item.amount, 0);",
      "}",
      "",
      "export function search" + Title + "s(items: " + Title + "[], term: string): " + Title + "[] {",
      "  const needle = term.trim().toLowerCase();",
      "  if (!needle) return items;",
      "  return items.filter((item) => item.name.toLowerCase().includes(needle));",
      "}",
      "",
      "export function latest" + Title + "s(items: " + Title + "[], count = 5): " + Title + "[] {",
      "  return [...items]",
      "    .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))",
      "    .slice(0, count);",
      "}",
    ]),
    file(base + "/format.ts", "typescript", "Display strings for " + key, [
      'import { formatCurrency, formatDate } from "../../lib/format";',
      'import type { ' + Title + ' } from "./types";',
      "",
      "export function describe" + Title + "(item: " + Title + "): string {",
      '  return item.name + " · " + formatCurrency(item.amount);',
      "}",
      "",
      "export function " + camel(key) + "Age(item: " + Title + "): string {",
      '  return "Updated " + formatDate(item.updatedAt);',
      "}",
      "",
      "export function " + camel(key) + "Summary(items: " + Title + "[]): string {",
      '  if (items.length === 0) return "No ' + key + ' yet";',
      '  return items.length + " ' + key + ' · " + formatCurrency(items.reduce((sum, item) => sum + item.amount, 0));',
      "}",
    ]),
    file(base + "/components/" + Title + "List.tsx", "typescript", "List view", [
      'import { Card } from "../../../components/Card";',
      'import { DataTable } from "../../../components/DataTable";',
      'import { describe' + Title + " } from \"../format\";",
      'import type { ' + Title + ' } from "../types";',
      "",
      "export function " + Title + "List({ items }: { items: " + Title + "[] }) {",
      '  if (items.length === 0) return <Card title="' + entity.title + '">Nothing here yet.</Card>;',
      "",
      "  return (",
      '    <Card title="' + entity.title + '">',
      "      <DataTable",
      '        columns={["Name", "Status", "Detail"]}',
      "        rows={items.map((item) => [",
      "          item.name,",
      "          item.status,",
      "          describe" + Title + "(item),",
      "        ])}",
      "      />",
      "    </Card>",
      "  );",
      "}",
    ]),
    file(base + "/components/" + Title + "Form.tsx", "typescript", "Create form", [
      'import { useState } from "react";',
      'import { Button } from "../../../components/Button";',
      'import { Input } from "../../../components/Input";',
      'import { empty' + Title + 'Draft } from "../types";',
      'import type { ' + Title + 'Draft } from "../types";',
      "",
      "export function " + Title + "Form({ onCreate }: { onCreate: (draft: " + Title + "Draft) => void }) {",
      "  const [draft, setDraft] = useState<" + Title + "Draft>(empty" + Title + "Draft());",
      "",
      "  return (",
      "    <form",
      '      className="stack"',
      "      onSubmit={(event) => {",
      "        event.preventDefault();",
      "        if (!draft.name.trim()) return;",
      "        onCreate(draft);",
      "        setDraft(empty" + Title + "Draft());",
      "      }}",
      "    >",
      "      <Input",
      '        label="Name"',
      "        value={draft.name}",
      "        onChange={(name) => setDraft({ ...draft, name })}",
      "      />",
      "      <Input",
      '        label="Amount"',
      '        type="number"',
      "        value={String(draft.amount)}",
      "        onChange={(amount) => setDraft({ ...draft, amount: Number(amount) })}",
      "      />",
      '      <Button type="submit">Add ' + entity.singular + "</Button>",
      "    </form>",
      "  );",
      "}",
    ]),
    file(base + "/components/" + Title + "Detail.tsx", "typescript", "Detail view", [
      'import { Card } from "../../../components/Card";',
      'import { Badge } from "../../../components/Badge";',
      'import { ' + camel(key) + 'Age } from "../format";',
      'import type { ' + Title + ' } from "../types";',
      "",
      "export function " + Title + "Detail({ item }: { item: " + Title + " }) {",
      "  return (",
      '    <Card title={item.name}>',
      "      <Badge tone={item.status === \"closed\" ? \"neutral\" : \"good\"}>{item.status}</Badge>",
      '      <p className="muted">{' + camel(key) + 'Age(item)}</p>',
      "      <p>{item.amount.toFixed(2)}</p>",
      "    </Card>",
      "  );",
      "}",
    ]),
    file(
      base + "/__tests__/" + key + ".test.ts",
      "typescript",
      "Selectors test for " + key,
      [
        'import { describe, expect, it } from "vitest";',
        'import { active' + Title + "s, latest" + Title + "s, search" + Title + "s, totalAmount } from \"../selectors\";",
        'import type { ' + Title + ' } from "../types";',
        "",
        "function sample(): " + Title + "[] {",
        "  return [",
        "    {",
        '      id: "1",',
        '      name: "Alpha",',
        '      status: "active",',
        "      amount: 120,",
        '      createdAt: "2026-01-01T00:00:00.000Z",',
        '      updatedAt: "2026-02-01T00:00:00.000Z",',
        "    },",
        "    {",
        '      id: "2",',
        '      name: "Beta",',
        '      status: "closed",',
        "      amount: 80,",
        '      createdAt: "2026-01-02T00:00:00.000Z",',
        '      updatedAt: "2026-03-01T00:00:00.000Z",',
        "    },",
        "  ];",
        "}",
        "",
        'describe("' + key + ' selectors", () => {',
        '  it("drops closed items", () => {',
        "    expect(active" + Title + "s(sample())).toHaveLength(1);",
        "  });",
        "",
        '  it("sums amounts", () => {',
        "    expect(totalAmount(sample())).toBe(200);",
        "  });",
        "",
        '  it("searches by name", () => {',
        '    expect(search' + Title + "s(sample(), \"alpha\")).toHaveLength(1);",
        "  });",
        "",
        '  it("sorts by last update", () => {',
        '    expect(latest' + Title + "s(sample())[0].id).toBe(\"2\");",
        "  });",
        "});",
      ],
    ),
  ];
}

export function reactFiles(ctx: BuildContext): GenFile[] {
  return [...scaffold(ctx), ...ctx.entities.flatMap((entity) => entityFiles(entity))];
}
