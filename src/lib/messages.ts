/**
 * The client side of chat encryption: write paths that encrypt before the
 * request leaves the browser.
 *
 * These are wrappers rather than scattered `encryptText` calls for one reason
 * — there are roughly twenty places in the app that write a user turn, and
 * every one of them would have to remember. Wrapping the mutation itself
 * means a call site keeps its exact shape (`await appendMessage({...})`) while
 * the plaintext never reaches the network. A missing key becomes a thrown
 * error at one chokepoint instead of a silently stored secret at twenty.
 *
 * Only user-authored text is encrypted. Assistant replies pass through
 * untouched: the model wrote them, and the whole design accepts that the model
 * reads what you send it.
 */
import { useMutation, useQuery } from "convex/react";
import { useCallback } from "react";
import type { FunctionReference } from "convex/server";
import { api } from "@/convex/_generated/api";
import { encryptText, rememberPlaintext } from "./e2e";
import { useE2EKey } from "./use-e2e";

/** What the UI matches on to decide "show the passphrase dialog" instead of a generic failure. */
export const PASSPHRASE_REQUIRED = "passphrase-required";

type ArgsOf<F> = F extends FunctionReference<"mutation", "public", infer A, any>
  ? A
  : never;
type ReturnOf<F> = F extends FunctionReference<"mutation", "public", any, infer R>
  ? R
  : never;

/**
 * The key for this account, plus whether we know yet.
 *
 * `material === undefined` means Convex is still answering — a different state
 * from "no passphrase exists", and conflating the two would prompt a brand-new
 * user for a passphrase they have never been asked to create.
 */
function useWriterKey() {
  const material = useQuery(api.chats.keyMaterial);
  const key = useE2EKey(material?.salt);
  return {
    key,
    loading: material === undefined,
    hasMaterial: !!material,
  };
}

function requireKey(
  key: CryptoKey | null,
  loading: boolean,
): CryptoKey {
  if (key) return key;
  throw new Error(
    loading ? "Checking your passphrase…" : PASSPHRASE_REQUIRED,
  );
}

/** Encrypt for a user turn, or refuse loudly. */
async function encryptUserText(
  key: CryptoKey | null,
  loading: boolean,
  text: string,
): Promise<string> {
  const cipher = await encryptText(requireKey(key, loading), text);
  // Seed the read cache so this message renders as typed on the very next
  // frame, instead of waiting for the async decrypt pass to catch up.
  rememberPlaintext(cipher, text);
  return cipher;
}

/**
 * Append a message. User turns are encrypted; assistant turns are not.
 *
 * The role decides, so a reply generated by the model stays readable to the
 * server (it needs to be — the transcript, search and export all read it)
 * while your own words do not.
 */
export function useAppendMessage() {
  const mutate = useMutation(api.chats.appendMessage);
  const { key, loading } = useWriterKey();
  type A = ArgsOf<typeof api.chats.appendMessage>;
  type R = ReturnOf<typeof api.chats.appendMessage>;
  return useCallback(
    async (args: A): Promise<R> => {
      const content =
        args.role === "user"
          ? await encryptUserText(key, loading, args.content)
          : args.content;
      return (await mutate({ ...args, content })) as R;
    },
    [mutate, key, loading],
  );
}

/**
 * Open a chat with a first message.
 *
 * The title is derived from the sentence *before* it is encrypted — the
 * server can no longer do that derivation itself, because by the time it sees
 * the text it is ciphertext.
 */
export function useStartWithMessage() {
  const mutate = useMutation(api.chats.startWithMessage);
  const { key, loading } = useWriterKey();
  type A = ArgsOf<typeof api.chats.startWithMessage>;
  type R = ReturnOf<typeof api.chats.startWithMessage>;
  return useCallback(
    async (args: A): Promise<R> => {
      const content = await encryptUserText(key, loading, args.content);
      const title = args.content.length > 60
        ? `${args.content.slice(0, 60).trimEnd()}…`
        : args.content;
      const titleCiphertext = await encryptUserText(key, loading, title);
      return (await mutate({
        ...args,
        content,
        titleCiphertext,
      })) as R;
    },
    [mutate, key, loading],
  );
}

/**
 * Rename a chat.
 *
 * Titles are derived from your words too, so they carry the same obligation —
 * an unencrypted title would leak the first line of the conversation straight
 * into the sidebar and the search index.
 */
export function useRenameSession() {
  const mutate = useMutation(api.chats.renameSession);
  const { key, loading } = useWriterKey();
  type A = ArgsOf<typeof api.chats.renameSession>;
  type R = ReturnOf<typeof api.chats.renameSession>;
  return useCallback(
    async (args: A): Promise<R> => {
      const title = await encryptUserText(key, loading, args.title);
      return (await mutate({ ...args, title })) as R;
    },
    [mutate, key, loading],
  );
}
