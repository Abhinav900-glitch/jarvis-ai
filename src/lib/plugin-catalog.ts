// ---------------------------------------------------------------------------
// The built-in skill catalogue.
//
// Settings → Plugins ships a few hand-written packs, plus this: a broad
// catalogue of narrow skills. Each entry is one focused skill built from a
// category template plus the entry's own scope, so the catalogue stays a data
// table instead of 500 near-identical Markdown files.
//
// Bodies are produced on demand in `skillBodyFor` — the picker only needs the
// name, category and scope line to render, so a 500-entry list costs almost
// nothing until somebody actually builds a zip.
// ---------------------------------------------------------------------------

export interface SkillScope {
  /** Human name, e.g. "Postgres schema". */
  name: string;
  /** What the skill covers, in one phrase. Used inside the body. */
  focus: string;
  /** Category label, which chooses the method and checks. */
  category: string;
}

interface CategoryInfo {
  /** One line describing what this family of skills is for. */
  blurb: string;
  /** Ordered method; `{focus}` is replaced with the entry's scope. */
  method: string[];
  /** Things to verify before answering; `{focus}` is replaced too. */
  checks: string[];
  /** What the answer should look like. */
  output: string;
}

