const FALLBACK_CATEGORY: CategoryInfo = CATEGORY_INFO.Operations;

/** Replace `{focus}` in a template line. */
function fill(line: string, focus: string): string {
  return line.replace(/\{focus\}/g, focus);
}

/**
 * Build the Markdown for one catalogue skill. Called when a zip is assembled,
 * not when the picker renders, so a long catalogue stays cheap.
 */
export function skillBodyFor(scope: SkillScope): string {
  const info = CATEGORY_INFO[scope.category] ?? FALLBACK_CATEGORY;
  const lines: string[] = [
    `# ${scope.name}`,
    "",
    `A focused working method for ${scope.focus}. Part of the ${scope.category.toLowerCase()} shelf of the built-in catalogue.`,
    "",
    "## When to use it",
    "",
    `Reach for this when a task turns on ${scope.focus}. It is deliberately narrow: if the question is really about something else, say so and switch skills instead of stretching this one.`,
    "",
    "## Method",
    "",
    ...info.method.map((step, i) => `${i + 1}. ${fill(step, scope.focus)}`),
    "",
    "## Checks before answering",
    "",
    ...info.checks.map((check) => `- ${fill(check, scope.focus)}`),
    "",
    "## Output",
    "",
    info.output,
    "",
    "## Ground rules",
    "",
    "- Separate what you verified from what you inferred, every time.",
    "- If a number, name or date is uncertain, write that it is uncertain instead of inventing one.",
    "- Prefer the smallest correct next step over a comprehensive plan nobody will follow.",
    "",
  ];
  return lines.join("\n");
}

